/* 📦 프로젝트 문법 — 프로젝트 하나를 통째로 글 한 덩어리로 적는다.
 *
 * 이 프로그램의 핵심 약속:
 *   **화면에서 되는 일은 전부 글로도 쓸 수 있어야 한다.**
 * 그래야 클로드 같은 LLM이 글 한 덩어리를 만들어 주면 수백 편을 한 번에 굽는다.
 *
 * 생김새 ──────────────────────────────────────────
 *   프로젝트: 댕댕이 시리즈
 *   비율: 9:16
 *   해상도: 1280
 *   초당장수: 30
 *   음악: 포근한밤.mp3   소리크기:0.7  여닫이:1.5초
 *   이어붙이기: 사이 0.4초
 *   굽기: 각각            # 각각 | 이어서 | 둘다 | 안함
 *
 *   == 이야기 고구마 굽기
 *   장면 공원 잔디밭
 *     우리집 강아지 등장 가운데
 *     자막 "고구마를 구워 볼까요?"
 *
 *   == 이야기 밤바다 산책
 *   장면 밤바다
 *     ...
 * ────────────────────────────────────────────────
 * `==` 앞은 프로젝트 설정, `== 이야기 <이름>` 부터는 그 이야기의 대본이다.
 * 이야기 대본 안의 문법은 지금 쓰던 것 그대로다 (script.js).
 */
import { parseScript } from "./script.js";

/** 이야기 한 편이 시작되는 줄 */
const 머리 = /^\s*={2,}\s*(?:이야기|스토리|편)?\s*(.*?)\s*=*\s*$/;

/** 프로젝트 설정으로 받는 말 (그 밖의 `키: 값` 은 이야기 쪽으로 넘긴다) */
export const PROJECT_KEYS = {
  "프로젝트": "이름", "제목": "이름",
  "비율": "비율", "해상도": "해상도", "긴변": "해상도",
  "초당장수": "fps", "fps": "fps", "화질": "화질",
  "배경색": "배경색", "여닫이": "여닫이",
  "음악": "음악", "음악프롬프트": "음악프롬프트", "음악분위기": "음악분위기",
  "이어붙이기": "이어붙이기", "굽기": "굽기", "메모": "메모",
};

const 숫자 = (v, 기본) => {
  const n = parseFloat(String(v).replace(/[^\d.\-]/g, ""));
  return Number.isFinite(n) ? n : 기본;
};

/**
 * 프로젝트 글 → 구조
 * @returns {{설정, 이야기:[{이름, 글, line}], 오류:[]}}
 */
export function parseProject(src) {
  const 줄들 = String(src || "").split(/\r?\n/);
  const 설정 = {}, 이야기 = [], 오류 = [];
  let 지금 = null;

  줄들.forEach((raw, i) => {
    const lineNo = i + 1;
    const m = raw.match(머리);
    if (m && /^\s*=/.test(raw)) {
      지금 = { 이름: (m[1] || `이야기 ${이야기.length + 1}`).trim(), 글: [], line: lineNo };
      이야기.push(지금);
      return;
    }
    if (지금) { 지금.글.push(raw); return; }

    // 아직 이야기가 시작되지 않았으면 프로젝트 설정
    const kv = raw.match(/^\s*([^\s:]+)\s*:\s*(.*)$/);
    if (kv && PROJECT_KEYS[kv[1]]) { 설정[PROJECT_KEYS[kv[1]]] = kv[2].trim(); return; }
    if (kv) { 설정[kv[1]] = kv[2].trim(); return; }        // 모르는 것도 담아 둔다
    if (raw.trim() && !/^\s*#/.test(raw))
      오류.push({ line: lineNo, msg: `이야기 앞에는 설정만 쓸 수 있습니다: "${raw.trim()}"` });
  });

  /* 자막 꾸미기(`자막차림표:` `자막글꼴:` …)는 **편마다 쓰는 것**이다.
     프로젝트 첫머리에 한 번 적으면 모든 편이 따르는 것이 자연스러운데,
     편의 대본은 따로 저장되므로 그대로 두면 통째로 사라진다.
     그래서 여기서 각 편의 글 맨 앞에 붙여 내려보낸다. */
  const 자막설정 = Object.entries(설정)
    .filter(([k, v]) => /^자막/.test(k) && String(v).trim())
    .map(([k, v]) => `${k}: ${v}`);

  return {
    설정: 정리(설정),
    이야기: 이야기.map(s => {
      const 글 = s.글.join("\n").trim();
      return { 이름: s.이름,
               글: 자막설정.length ? 자막설정.join("\n") + "\n\n" + 글 : 글,
               line: s.line };
    }),
    오류,
  };
}

/** 설정 글자 → 쓰기 좋은 값 */
function 정리(설정) {
  const 음악 = String(설정.음악 || "");
  const 소리크기 = 음악.match(/소리크기\s*:\s*([\d.]+)/);
  const 여닫이M = 음악.match(/여닫이\s*:\s*([\d.]+)/);
  const 이어 = String(설정.이어붙이기 || "");
  return {
    이름: 설정.이름 || "",
    비율: 설정.비율 || "9:16",
    해상도: 숫자(설정.해상도, 1280),
    fps: 숫자(설정.fps, 30),
    화질: 설정.화질 || "보통",
    배경색: 설정.배경색 || "",
    여닫이: 설정.여닫이 || "",
    /* 음악 이름은 **띄어쓸 수 있다** (`산책 배경음`).
       예전에는 첫 낱말만 잘라 써서 `산책` 이 되고, 그런 음악이 없어 조용히 소리가 빠졌다.
       뒤에 붙는 꼬리표(`소리크기:` `여닫이:`)만 떼어 내고 나머지를 통째로 이름으로 본다. */
    음악: { 파일: 음악.replace(/\s*(소리크기|여닫이)\s*:\s*[\d.]+초?/g, "").trim(),
            소리크기: 소리크기 ? parseFloat(소리크기[1]) : 0.7,
            여닫이: 여닫이M ? parseFloat(여닫이M[1]) : 1.5 },
    음악프롬프트: 설정.음악프롬프트 || "",
    음악분위기: 설정.음악분위기 || "",
    이어붙이기: { 사이: 숫자((이어.match(/사이\s*([\d.]+)/) || [])[1], 0.3),
                  함: !!이어 && !/안\s*함|없음/.test(이어) },
    굽기: (설정.굽기 || "안함").replace(/\s/g, ""),        // 각각 | 이어서 | 둘다 | 안함
    메모: 설정.메모 || "",
  };
}

/** 구조 → 글 (되돌리기) */
export function writeProject(설정 = {}, 이야기 = []) {
  const L = [];
  if (설정.이름) L.push(`프로젝트: ${설정.이름}`);
  L.push(`비율: ${설정.비율 || "9:16"}`);
  L.push(`해상도: ${설정.해상도 || 1280}`);
  L.push(`초당장수: ${설정.fps || 30}`);
  if (설정.화질) L.push(`화질: ${설정.화질}`);
  if (설정.배경색) L.push(`배경색: ${설정.배경색}`);
  if (설정.여닫이) L.push(`여닫이: ${설정.여닫이}`);
  const 음 = 설정.음악 || {};
  if (음.파일) L.push(`음악: ${음.파일}   소리크기:${음.소리크기 ?? 0.7}  여닫이:${음.여닫이 ?? 1.5}초`);
  if (설정.음악프롬프트) L.push(`음악프롬프트: ${설정.음악프롬프트}`);
  if (설정.이어붙이기?.함) L.push(`이어붙이기: 사이 ${설정.이어붙이기.사이 ?? 0.3}초`);
  if (설정.굽기 && 설정.굽기 !== "안함") L.push(`굽기: ${설정.굽기}`);
  for (const s of 이야기) {
    L.push("", `== 이야기 ${s.이름 || s.name || ""}`.trimEnd(), (s.글 ?? s.text ?? "").trim());
  }
  return L.join("\n") + "\n";
}

/** 이야기까지 다 읽어 무엇이 필요한지 미리 알려 준다 (실행 전 점검) */
export function inspectProject(src) {
  const p = parseProject(src);
  const 편 = p.이야기.map(s => {
    const r = parseScript(s.글);
    return {
      이름: s.이름, line: s.line,
      장면수: r.scenes.length,
      오류: r.errors.map(e => ({ ...e, line: e.line + s.line })),
      배경: [...new Set(r.scenes.map(x => x.bg).filter(Boolean))],
    };
  });
  return {
    ...p, 편,
    오류: [...p.오류, ...편.flatMap(e => e.오류)],
    이야기수: 편.length,
    장면수: 편.reduce((a, b) => a + b.장면수, 0),
  };
}

/** 지금 프로젝트를 문법 글로 뽑아 준다 (LLM 에게 보여 주거나 복사할 때) */
export function projectToText(item, stories) {
  const e = item.encode || {}, t = item.timeline || {};
  return writeProject({
    이름: item.name, 비율: e.비율, 해상도: e.긴변, fps: e.fps, 화질: e.화질,
    음악: { 파일: t.음악?.파일 || "", 소리크기: t.음악?.소리크기, 여닫이: t.음악?.여닫이 },
    이어붙이기: { 함: (t.순서 || []).length > 1, 사이: t.사이 },
    굽기: "안함",
  }, (stories || []).map(s => ({ 이름: s.name, 글: s.text || "" })));
}
